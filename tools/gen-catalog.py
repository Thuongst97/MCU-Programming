"""Build the example catalog from each examples/NN-*/README.md front matter.

  python3 tools/gen-catalog.py           # write examples/README.md, site/assets/js/data/examples.js
                                         # and site/assets/js/data/versions.js (from tools/versions.json)
  python3 tools/gen-catalog.py --check   # CI: fail if any of them is out of date

Pages never type a tool version (CLAUDE.md rule 4): they write <span data-version="cmake"></span> and
core.js fills it from versions.js, which is generated here from tools/versions.json.

Front matter (between --- lines) uses a small YAML subset: `key: value` and `key: [a, b]`.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ["id", "title", "modules", "peripherals", "flavor", "pins", "hw", "tested_on"]


def parse(readme):
    text = readme.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit(f"{readme.relative_to(ROOT)}: missing front matter")
    meta = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        v = v.strip()
        unq = lambda x: x[1:-1] if len(x) >= 2 and x[0] == x[-1] == '"' else x
        if v.startswith("["):
            meta[k.strip()] = [unq(x.strip()) for x in v[1:-1].split(",") if x.strip()]
        else:
            meta[k.strip()] = unq(v)
    missing = [f for f in FIELDS if f not in meta]
    if missing:
        raise SystemExit(f"{readme.relative_to(ROOT)}: front matter lacks {missing}")
    meta["folder"] = readme.parent.name
    return meta


def render(items):
    rows = "\n".join(
        f"| [{e['id']}]({e['folder']}/) | {e['title']} | {', '.join(e['peripherals'])} | {e['flavor']} | "
        f"{', '.join(e['hw']) or '—'} | {', '.join(e['tested_on']) or 'not yet'} |"
        for e in items)
    md = ("# Examples\n\nGenerated by `tools/gen-catalog.py` from each example's README front matter — do not edit.\n"
          "Every example targets the NUCLEO-G474RE (STM32G474RET6, on-board ST-LINK/V3E) and builds with\n"
          "`cmake --preset nucleo-debug && cmake --build --preset nucleo-debug`.\n"
          "There is no simulator for the STM32G4: pure logic is host-tested, the rest needs the board.\n\n"
          "| # | Example | Peripherals | Flavor | Extra hardware | Tested on hardware |\n"
          "|---|---|---|---|---|---|\n" + rows + "\n")
    js = ("/* SPDX-License-Identifier: MIT\n   Generated by tools/gen-catalog.py from examples/*/README.md — do not edit. */\n"
          "window.MCU_DATA = window.MCU_DATA || {};\nwindow.MCU_DATA.examples = "
          + json.dumps(items, indent=1, ensure_ascii=False) + ";\n")
    return md, js


def versions_js():
    v = json.loads((ROOT / "tools/versions.json").read_text(encoding="utf-8"))
    keep = ("name", "version", "alt", "url", "min")
    data = {"checked": v.get("checked"),
            "tools": {k: {f: t[f] for f in keep if f in t} for k, t in v["tools"].items()},
            "specs": v.get("specs", {}),
            "third_party": {k: {"name": t["name"], "version": t["tag"], "url": t["repo"]} for k, t in v.get("third_party", {}).items()}}
    return ("/* SPDX-License-Identifier: MIT\n   Generated by tools/gen-catalog.py from tools/versions.json — do not edit. */\n"
            "window.MCU_DATA = window.MCU_DATA || {};\nwindow.MCU_DATA.versions = "
            + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")


def main():
    items = [parse(p) for p in sorted(ROOT.glob("examples/[0-9][0-9]-*/README.md"))]
    md, js = render(items)
    targets = {ROOT / "examples/README.md": md, ROOT / "site/assets/js/data/examples.js": js,
               ROOT / "site/assets/js/data/versions.js": versions_js()}
    if "--check" in sys.argv:
        stale = [p for p, t in targets.items() if not p.is_file() or p.read_text(encoding="utf-8") != t]
        for p in stale:
            print(f"ERROR {p.relative_to(ROOT)} is out of date — run python3 tools/gen-catalog.py")
        print(f"gen-catalog: {len(items)} example(s), {len(stale)} stale file(s)")
        sys.exit(1 if stale else 0)
    for p, t in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
