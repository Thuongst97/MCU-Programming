def columns(rows):
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), rows
    return [sum((1 << y) for y in range(7) if rows[y][x] == "#") for x in range(5)]


def render():
    chars = "".join(GLYPHS)
    lines = ["/* SPDX-License-Identifier: MIT",
             " * GENERATED by tools/gen-font.py from the course's own glyph drawings: do not edit.",
             " * 5x7 pixels per glyph, 5 column bytes, bit 0 = top row (SSD1306 page layout). */",
             '#include "font5x7.h"', "",
             f'const char font5x7_chars[] = "{chars}";', "",
             f"const uint8_t font5x7[{len(GLYPHS)}][5] = {{"]
    for ch, rows in GLYPHS.items():
        cols = ", ".join(f"0x{c:02X}" for c in columns(rows))
        lines.append(f"    {{{cols}}},   /* '{ch}' */")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print(f"gen-font: {'up to date' if ok else 'STALE: run python3 tools/gen-font.py'}")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(GLYPHS)} glyphs)")


if __name__ == "__main__":
    main()
