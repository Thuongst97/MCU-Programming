"""Turn a built ELF into the JSON the memory-map visualizer draws (PLAN.md §9.7).

  python3 tools/elf2memmap.py --all            # regenerate site/assets/data/memmap/*.json
  python3 tools/elf2memmap.py --all --check    # CI: fail if the committed JSON is out of date

Uses the toolchain's objdump (section VMA/LMA/size), nm (symbols) and the linker map file
(memory regions), so the site always shows the layout of the code that CI actually built.
The JSON is committed (pages work from file:// without a build) and regenerated by this tool only.
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site/assets/data/memmap"
# ELFs shown on the site (relative to the build directory) -> JSON name.
TARGETS = {
    "examples/00-bluepill-blink-uart/bare/00-bluepill-blink-uart.elf": "00-bluepill-blink-uart",
    "examples/00-bluepill-blink-uart/hal/00-bluepill-blink-uart-hal.elf": "00-bluepill-blink-uart-hal",
    "examples/12-uart-bootloader/12-bootloader.elf": "12-bootloader",
    "examples/12-uart-bootloader/12-application.elf": "12-application",
}
SYMBOLS = ["g_vector_table", "Reset_Handler", "main", "_sidata", "_sdata", "_edata", "_sbss", "_ebss",
           "_estack", "_etext", "end", "SystemCoreClock"]


def tool(name):
    t = shutil.which(f"arm-none-eabi-{name}")
    if not t:
        sys.exit(f"arm-none-eabi-{name} not found on PATH")
    return t


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def regions(map_path):
    text = map_path.read_text(encoding="utf-8", errors="replace")
    block = text.split("Memory Configuration", 1)[1].split("Linker script and memory map", 1)[0]
    out = []
    for name, origin, length in re.findall(r"^(\w+)\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)", block, re.M):
        if name != "Name" and name != "*default*":
            out.append({"name": name, "origin": int(origin, 16), "length": int(length, 16)})
    return out


def sections(elf):
    out = []
    lines = run(tool("objdump"), "-h", "-w", str(elf)).splitlines()
    for line in lines:
        m = re.match(r"\s*\d+\s+(\S+)\s+([0-9a-f]+)\s+([0-9a-f]+)\s+([0-9a-f]+)\s+[0-9a-f]+\s+\S+\s+(.*)$", line)
        if not m:
            continue
        name, size, vma, lma, flags = m.group(1), int(m.group(2), 16), int(m.group(3), 16), int(m.group(4), 16), m.group(5)
        if "ALLOC" not in flags:
            continue
        out.append({"name": name, "vma": vma, "lma": lma, "size": size, "load": "LOAD" in flags})
    return out


def symbols(elf):
    want, out, biggest = set(SYMBOLS), [], []
    for line in run(tool("nm"), "-S", "--size-sort", "-C", str(elf)).splitlines() + run(tool("nm"), str(elf)).splitlines():
        parts = line.split()
        if len(parts) == 4:
            addr, size, kind, name = parts
            if kind in "tT" and int(size, 16) > 0:
                biggest.append({"name": name, "value": int(addr, 16), "size": int(size, 16)})
        elif len(parts) == 3:
            addr, kind, name = parts
        else:
            continue
        if name in want:
            want.discard(name)
            out.append({"name": name, "value": int(addr, 16)})
    biggest.sort(key=lambda s: -s["size"])
    return sorted(out, key=lambda s: s["value"]), biggest[:8]


def gcc_version():
    return run(tool("gcc"), "--version").splitlines()[0]


def build(elf, name):
    map_path = elf.with_suffix(".map")
    syms, biggest = symbols(elf)
    return {
        "name": name,
        "elf": elf.name,
        "toolchain": gcc_version(),
        "regions": regions(map_path),
        "sections": sections(elf),
        "symbols": syms,
        "largest_functions": biggest,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--build-dir", default="build/bluepill-debug")
    a = ap.parse_args()
    if not a.all:
        ap.error("use --all")
    build_dir = ROOT / a.build_dir
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for rel, name in TARGETS.items():
        elf = build_dir / rel
        if not elf.is_file():
            if (OUT / f"{name}.json").is_file():
                stale.append(f"{name}: {rel} was not built")
            continue
        text = json.dumps(build(elf, name), indent=1) + "\n"
        dest = OUT / f"{name}.json"
        if a.check:
            if not dest.is_file() or dest.read_text(encoding="utf-8") != text:
                stale.append(f"{name}: out of date — run python3 tools/elf2memmap.py --all")
        else:
            dest.write_text(text, encoding="utf-8")
            print(f"wrote {dest.relative_to(ROOT)}")
    for s in stale:
        print("ERROR", s)
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
