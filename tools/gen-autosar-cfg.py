"""Generate the per-module MemMap headers and Compiler_Cfg.h of an AUTOSAR-style project.

In a real project the BSW configurator writes these files; here this script plays that role so
they are consistent and never edited by hand.

  python3 tools/gen-autosar-cfg.py capstone/turnlight/stage3-autosar/cfg          # write
  python3 tools/gen-autosar-cfg.py --check capstone/turnlight/stage3-autosar/cfg  # CI

The module list is read from <cfg>/modules.txt: one "<Msn> <MSN>" pair per line, e.g. "Dio DIO".
"""
import argparse
import sys
from pathlib import Path

SECTIONS = ["CODE", "VAR_CLEARED_UNSPECIFIED", "VAR_INIT_UNSPECIFIED", "CONST_UNSPECIFIED", "CONFIG_DATA_UNSPECIFIED"]
CLASSES = ["CODE", "VAR", "CONST", "APPL_DATA", "APPL_CONST", "APPL_CODE"]
BANNER = """/* SPDX-License-Identifier: MIT
 * MCU Academy — AUTOSAR-style teaching code. NOT an AUTOSAR-conformant implementation.
 * Spec reference : AUTOSAR CP R25-11, {doc}
 * In production  : GENERATED by the BSW configurator. Here: GENERATED by tools/gen-autosar-cfg.py, do not edit.
 */
"""


def memmap(msn, MSN):
    out = [BANNER.format(doc="AUTOSAR_CP_SWS_MemoryMapping"),
           f"/* Memory mapping of {msn}. No include guard: included before and after every section. */"]
    first = True
    for sec in SECTIONS:
        for kind, flag in (("START", "MEMMAP_DO_START"), ("STOP", "MEMMAP_DO_STOP")):
            out += [f"#{'if' if first else 'elif'} defined({MSN}_{kind}_SEC_{sec})",
                    f"#  undef {MSN}_{kind}_SEC_{sec}", f"#  define {flag}"]
            first = False
    out += ["#else", f'#  error "{msn}_MemMap.h: unknown memory section"', "#endif", '#include "MemMap_Check.h"', ""]
    return "\n".join(out)


def compiler_cfg(mods):
    out = [BANNER.format(doc="AUTOSAR_CP_SWS_CompilerAbstraction"), "#ifndef COMPILER_CFG_H", "#define COMPILER_CFG_H", "",
           "/* Memory classes of every module. On the Cortex-M3 all of them are empty. */",
           "#define AUTOSAR_COMSTACKDATA"]
    for _, MSN in mods:
        out += [f"#define {MSN}_{c}" for c in CLASSES]
    out += ["", "#endif", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cfg", type=Path)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    mods = [tuple(l.split()) for l in (a.cfg / "modules.txt").read_text(encoding="utf-8").splitlines()
            if l.strip() and not l.startswith("#")]
    files = {f"{msn}_MemMap.h": memmap(msn, MSN) for msn, MSN in mods}
    files["Compiler_Cfg.h"] = compiler_cfg(mods)
    stale = []
    for name, text in files.items():
        p = a.cfg / name
        if a.check:
            if not p.is_file() or p.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            p.write_text(text, encoding="utf-8")
    if a.check and stale:
        print("gen-autosar-cfg: out of date: " + ", ".join(stale) + " — run python3 tools/gen-autosar-cfg.py " + str(a.cfg))
        return 1
    print(f"gen-autosar-cfg: {len(files)} file(s) {'checked' if a.check else 'written'} in {a.cfg}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
